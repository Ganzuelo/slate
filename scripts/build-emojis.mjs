import fs from 'node:fs/promises';

// Pinned Unicode 17.0 source; builds never fetch from the network.
export async function buildEmojis() {
 const root = new URL('../',import.meta.url);
 const source = await fs.readFile(new URL('research/unicode/emoji-test.txt',root),'utf8');
 const license = await fs.readFile(new URL('public/vendor/LICENSE.unicode.txt',root),'utf8');
 let group='',subgroup=''; const entries=[];
 for(const line of source.split(/\r?\n/)) {
  if(line.startsWith('# group: '))group=line.slice(9);
  if(line.startsWith('# subgroup: '))subgroup=line.slice(12);
  const match=/^([A-F0-9 ]+)\s*; fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/.exec(line);
  if(!match)continue;
  const points=match[1].trim().split(/\s+/).map(code=>parseInt(code,16));
  const id='emoji:'+points.map(point=>point.toString(16)).join('-');
  entries.push([id,String.fromCodePoint(...points),match[3],(group+' '+subgroup).toLowerCase()]);
 }
 if(entries.length<3000 || new Set(entries.map(item=>item[0])).size!==entries.length)throw new Error('Unexpected Unicode emoji catalog.');
 await fs.writeFile(new URL('public/emoji-data.js',root),'/*! Unicode 17.0 emoji data — generated by scripts/build-emojis.mjs.\n'+license.replaceAll('*/','* /')+'*/\nexport const emojis = '+JSON.stringify(entries)+'.map(([id,glyph,name,keywords])=>Object.freeze({id,glyph,name,keywords}));\n');
 console.log('Built '+entries.length+' local Unicode emoji choices.');
}
